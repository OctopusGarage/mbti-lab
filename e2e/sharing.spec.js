import { test, expect, CANONICAL, seedResult, language } from './helpers.js'

test('share dialog traps focus, protects private scores, copies and falls back after clipboard denial', async ({ page }) => {
  await seedResult(page)
  await language(page, 'en')
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async text => { window.copiedText = text } } }))
  await page.locator('.dock-share').focus()
  await page.locator('.dock-share').press('Enter')
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.locator('.sp-close')).toBeFocused()
  expect(await page.locator('#app').evaluate(element => element.inert)).toBe(true)
  await page.keyboard.press('Shift+Tab')
  await expect(page.locator('[data-action="copy-link"]')).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.locator('.sp-close')).toBeFocused()
  const caption = await page.locator('.share-text-preview').textContent()
  expect(caption).toContain(`${CANONICAL}/#/types?type=INFJ`)
  expect(caption).not.toMatch(/answers|percents|localhost|\d+%/)
  expect(caption.match(/https:\/\//g)).toHaveLength(1)
  await page.locator('[data-action="copy-result"]').click()
  expect(await page.evaluate(() => window.copiedText)).toBe(caption)
  await page.locator('[data-action="copy-link"]').click()
  expect(await page.evaluate(() => window.copiedText)).toBe(CANONICAL)
  await page.locator('[data-action="share-result-x"]').click()
  const opened = await page.evaluate(() => window.openedURLs)
  expect(opened).toHaveLength(1)
  expect(new URL(opened[0]).searchParams.get('text')).toBe(caption)
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw Error('denied') } } }))
  await page.locator('[data-action="copy-result"]').click()
  await expect(page.locator('textarea')).toHaveValue(caption)
  await expect(page.locator('textarea')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(await page.locator('#app').evaluate(element => element.inert)).toBe(false)
  await expect(page.locator('.dock-share')).toBeFocused()
  await page.goto('./#/types?type=INFJ')
  await page.locator('.dock-share').focus()
  await page.locator('.dock-share').press('Enter')
  await expect(page.locator('[data-action="save-image"]')).toHaveCount(0)
  await expect(page.locator('.share-text-preview')).toContainText('Explore the INFJ')
})
