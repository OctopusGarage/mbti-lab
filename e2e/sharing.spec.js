import { test, expect, CANONICAL, seedResult, language } from './helpers.js'

test('share dialog traps focus, protects private scores, copies and falls back after clipboard denial', async ({ page }) => {
  await seedResult(page)
  await language(page, 'en')
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async text => { window.copiedText = text } } }))
  await page.locator('.dock-share').focus()
  await page.locator('.dock-share').press('Enter')
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.locator('.sp-close')).toBeFocused()
  expect(await page.locator('#app').evaluate(element => element.inert)).toBe(true)
  await expect(page.locator('.export-preview a[download]')).toBeVisible()
  await page.keyboard.press('Shift+Tab')
  await expect(page.locator('.sp-secondary summary').last()).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.locator('.sp-close')).toBeFocused()
  await expect(page.locator('.qr-share')).toHaveCount(0)
  await page.locator('.sp-secondary summary').click()
  const caption = await page.locator('.share-text-preview').textContent()
  expect(caption).toContain(`${CANONICAL}/#/types?type=INFJ`)
  expect(caption).not.toMatch(/answers|percents|localhost|\d+%/)
  expect(caption.match(/https:\/\//g)).toHaveLength(1)
  await page.locator('[data-action="copy-result"]').click()
  expect(await page.evaluate(() => window.copiedText)).toBe(caption)
  await page.locator('[data-action="copy-link"]').click()
  expect(await page.evaluate(() => window.copiedText)).toBe(`${CANONICAL}/#/types?type=INFJ&lang=en`)
  await page.locator('[data-action="share-result-x"]').click()
  const opened = await page.evaluate(() => window.openedURLs)
  expect(opened).toHaveLength(1)
  expect(new URL(opened[0]).searchParams.get('text')).toBe(caption)
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw Error('denied') } } }))
  await page.locator('[data-action="copy-result"]').click()
  await expect(page.locator('textarea')).toHaveValue(caption)
  await expect(page.locator('textarea')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(await page.locator('#app').evaluate(element => element.inert)).toBe(false)
  await expect(page.locator('.dock-share')).toBeFocused()
  await page.goto('./#/types?type=INFJ')
  await expect(page.locator('.detail-back')).toBeVisible()
  await page.locator('.dock-share').focus()
  await page.locator('.dock-share').press('Enter')
  await expect(page.locator('[data-action="save-image"]')).toHaveCount(0)
  await expect(page.locator('.share-text-preview')).toContainText('Explore the INFJ')
})

test('result card stays in the dialog through native sharing, cancellation and reopening', async ({ page }) => {
  await seedResult(page)
  await language(page, 'en')
  await page.evaluate(() => {
    Object.defineProperty(navigator, 'canShare', { configurable: true, value: () => true })
    Object.defineProperty(navigator, 'share', { configurable: true, value: async ({ files }) => {
      window.sharedFile = { name: files[0].name, type: files[0].type, size: files[0].size }
      if (window.cancelShare) throw new DOMException('Cancelled', 'AbortError')
      if (window.failShare) throw new Error('Unavailable')
    } })
  })
  await page.locator('.dock-share').click()
  const preview = page.locator('[role="dialog"] .export-preview img')
  await expect(preview).toBeVisible()
  const image = await preview.getAttribute('src')
  await page.locator('.native-result').click()
  expect(await page.evaluate(() => window.sharedFile)).toMatchObject({ name: 'mbti-INFJ.png', type: 'image/png' })
  expect(await page.evaluate(() => window.sharedFile.size)).toBeGreaterThan(1000)
  await expect(preview).toBeVisible()
  await page.evaluate(() => { window.cancelShare = true })
  await page.locator('.native-result').click()
  await expect(page.locator('.export-preview [role="status"]')).toHaveCount(0)
  await page.evaluate(() => { window.cancelShare = false; window.failShare = true })
  await page.locator('.native-result').click()
  await expect(page.locator('.export-preview [role="status"]')).toBeVisible()
  await expect(page.locator('.export-preview a[download]')).toBeVisible()
  await page.locator('.sp-close').click()
  await page.locator('.dock-share').click()
  await expect(preview).toHaveAttribute('src', image)
})
