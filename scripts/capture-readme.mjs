import { chromium, expect } from '@playwright/test'
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const baseURL = 'https://octopusgarage.github.io/mbti-lab/'
const directory = new URL('../docs/images/', import.meta.url)
const capturedAt = new Date().toISOString()
const screenshots = []
await mkdir(directory, { recursive: true })
const browser = await chromium.launch()
try {
  const context = await browser.newContext({
    viewport: { width: 1080, height: 600 },
    deviceScaleFactor: 1,
    reducedMotion: 'reduce',
  })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('https://static.cloudflareinsights.com/**', route => route.abort())
  const response = await page.goto(`${baseURL}?capture=${Date.now()}`, { waitUntil: 'networkidle' })
  expect(response.status()).toBe(200)
  const entry = (await response.text()).match(/src="([^"]+\.js)"/)?.[1]
  expect(entry).toBeTruthy()
  await page.locator('.lang-toggle').click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')

  async function capture(file, description) {
    await page.evaluate(() => document.fonts.ready)
    await page.mouse.move(0, 0)
    await page.screenshot({ path: fileURLToPath(new URL(file, directory)), animations: 'disabled' })
    screenshots.push({ file, description, viewport: page.viewportSize(), locale: await page.locator('html').getAttribute('lang'), url: page.url() })
  }

  await expect(page.locator('.cards .start-card')).toHaveCount(2)
  await capture('home.png', 'Live home page with both assessment lengths')
  await page.setViewportSize({ width: 390, height: 844 })
  // Complete a real live assessment with scripted answers. No result payload,
  // UI text, CSS or document structure is injected into the hosted app.
  await page.clock.install()
  await page.clock.pauseAt(new Date(Date.now() + 60_000))
  await page.locator('.cards .start-card').first().click()
  for (let index = 0; index < 60; index++) {
    await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow', String(index + 1))
    if (index === 6) await capture('assessment.png', 'Question 7 of a scripted 60-question English assessment')
    await page.locator('.option').first().click()
    await page.clock.runFor(300)
  }
  await expect(page.locator('.type-letters')).toHaveText('ENFJ')
  await page.clock.resume()
  await expect(page.locator('.report-section')).toHaveCount(7)
  await capture('report.png', 'English ENFJ report computed from the scripted assessment')
  await page.locator('.dock-share').click()
  await page.locator('[data-action="save-image"]').click()
  const preview = page.locator('.export-preview img')
  await expect(preview).toBeVisible({ timeout: 60_000 })
  const png = await preview.getAttribute('src')
  expect(png).toMatch(/^data:image\/png;base64,/)
  await writeFile(new URL('share-card.png', directory), Buffer.from(png.split(',')[1], 'base64'))
  screenshots.push({ file: 'share-card.png', description: 'Unmodified PNG generated by the live export action', locale: 'en', type: 'ENFJ', url: page.url() })

  await page.goto(`${baseURL}#/types`)
  if (await page.locator('html').getAttribute('lang') !== 'zh') await page.locator('.lang-toggle').click()
  await expect(page.locator('.type-chip')).toHaveCount(16)
  await page.locator('input[type="search"]').fill('者')
  await expect(page.locator('.type-chip')).toHaveCount(5)
  await capture('types.png', 'Chinese type search for 者, showing five matching types')
  expect(errors, 'uncaught errors in the live app').toEqual([])
  await writeFile(new URL('capture.json', directory), `${JSON.stringify({ capturedAt, baseURL, entry, browser: browser.version(), sample: 'All A answers to the live 60-question assessment; demonstration only, not a personal assessment.', screenshots }, null, 2)}\n`)
  console.log(`Captured ${screenshots.length} live previews in docs/images/ from ${entry}`)
} finally {
  await browser.close()
}
